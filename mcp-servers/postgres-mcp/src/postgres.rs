//! The `wasmcloud:postgres@0.2.0` client: configuration, the host-call
//! operations (`query`, `execute`, `execute_batch`), and the error model
//! tools render.
//!
//! ## How the database is reached
//!
//! The component never dials Postgres. Cosmonic Desktop registers the
//! `wasmcloud:postgres` plugin in *multiplex* mode: the workload manifest
//! declares named host interfaces (`db`, `db-prepared`) whose resolved config
//! carries the connection URL (from the `postgres-mcp-url` secret ref, env
//! key `url`), the daemon owns a connection pool per URL, and this component
//! reaches it through the labeled imports in `wit/world.wit`. That is why the
//! workload needs no `allowedHosts`, no loopback grant and no volumes.
//!
//! ## Threading model
//!
//! Every binding call is a WASI p3 future and must run in component-model
//! context, never from tool (tokio) code. The operations below therefore
//! wrap the whole exchange — the call, consuming the row stream, awaiting the
//! completion future — in one [`crate::bridge::host_call`] closure and hand
//! back plain data (`Vec<Vec<PgValue>>`), so tools only ever see values.

use std::sync::Mutex;

use serde_json::{json, Value};

use crate::bridge::{self, HostCallError};
use crate::pgvalue::{retry_param, Param};

/// Generated guest bindings for `wit/world.wit`: the shared `types`
/// interface plus the two labeled imports (`db` = `query`, `db-prepared` =
/// `prepared`). Generated by the same wit-bindgen 0.61 runtime `wasip3`
/// uses, so the two async executors are one and the same.
pub mod bindings {
    wit_bindgen::generate!({
        path: "wit",
        world: "postgres-mcp",
        generate_all,
    });
}

