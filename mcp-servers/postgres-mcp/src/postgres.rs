/// Name of the Desktop secret reference that carries the connection URL.
pub const SECRET_REF: &str = "postgres-mcp-url";
/// The config key the daemon's postgres provider reads from the named host
/// interface — the secret ref MUST be registered with this `env`.
pub const SECRET_ENV: &str = "url";
/// Placeholder URL for the podman `mcp-pg` container on a developer machine.
pub const EXAMPLE_URL: &str = "postgres://mcp:mcp@127.0.0.1:5432/mcp?sslmode=disable";

/// The one-paragraph remediation used everywhere a credential problem is
/// reported: names the ref, the env key, where the value comes from and the
/// exact registration call.
pub fn credential_hint() -> String {
    format!(
        "The database URL comes from the Desktop secret ref `{SECRET_REF}` (env key `{SECRET_ENV}`), \
         resolved by the daemon when the workload binds — the component never sees it. Fix the \
         value (postgres://USER:PASSWORD@HOST:5432/DBNAME?sslmode=disable|require; percent-encode \
         special characters in the password; use 127.0.0.1 for a database on this machine — the \
         daemon dials from the host process) with `cosmonic_set_secret name={SECRET_REF} \
         uri=keychain://cosmonic/{SECRET_REF} env={SECRET_ENV} value=<url>` (or Desktop → Secrets), \
         then re-apply deploy/workload.yaml so the new value is picked up, and call server_info. \
         Local example: {EXAMPLE_URL}."
    )
}

