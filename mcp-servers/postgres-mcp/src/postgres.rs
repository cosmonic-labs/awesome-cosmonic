/// Rows straight from the host (converted to JSON by the tools).
#[derive(Debug)]
pub struct RawResult {
    pub columns: Vec<String>,
    pub rows: Vec<Vec<PgValue>>,
    /// More rows existed than `max_rows`; the stream was dropped early.
    pub truncated: bool,
}

/// Bind-format retries per call (each fixes one parameter's encoding).
const MAX_BIND_RETRIES: usize = 16;

/// "incorrect binary data format in bind parameter N" → N.
fn bind_param_index(message: &str) -> Option<usize> {
    let rest = message.split("bind parameter ").nth(1)?;
    rest.trim()
        .trim_end_matches(|c: char| !c.is_ascii_digit())
        .parse()
        .ok()
}

/// Whether the database rejected a parameter's *encoding* (as opposed to its
/// value): the cases the retry chain in [`crate::pgvalue`] can fix.
fn is_bind_format_error(err: &PgError) -> bool {
    let PgError::Db { code, message, .. } = err else {
        return false;
    };
    let m = message.to_ascii_lowercase();
    match code.as_str() {
        // invalid_binary_representation: wrong length, bad numeric sign, …
        "22P03" => true,
        // protocol_violation: too few bytes for the slot's type.
        "08P01" => m.contains("insufficient data") || m.contains("invalid message format"),
        // character_not_in_repertoire: a NUL byte from an integer encoding
        // landed in a text slot.
        "22021" => m.contains("0x00"),
        // invalid_parameter_value: jsonb version byte from text bytes.
        "22023" => m.contains("jsonb version"),
        _ => false,
    }
}

/// Re-encodes the parameter a bind-format error points at. When the message
/// names none (`08P01`, `22021`, `22023`) the culprit is only certain if
/// exactly one auto-typed parameter still has an untried encoding; with
/// several, guessing would thrash (and could land on a silent misread), so
/// the call fails with the attempts listed and typed params are the fix.
/// `false` when nothing is left to try.
fn retype(params: &mut [Param], err: &PgError) -> bool {
    if !is_bind_format_error(err) {
        return false;
    }
    let PgError::Db { message, .. } = err else {
        return false;
    };
    if let Some(index) = bind_param_index(message) {
        let Some(slot) = index.checked_sub(1).and_then(|i| params.get_mut(i)) else {
            return false;
        };
        return match retry_param(slot) {
            Some(next) => {
                *slot = next;
                true
            }
            None => false,
        };
    }
    let mut candidates = params
        .iter_mut()
        .filter(|p| retry_param(p).is_some())
        .collect::<Vec<_>>();
    match candidates.as_mut_slice() {
        [only] => {
            if let Some(next) = retry_param(only) {
                **only = next;
                return true;
            }
            false
        }
        _ => false,
    }
}

/// Whether an unindexed bind error could not be attributed to one parameter.
fn ambiguous_bind(params: &[Param], err: &PgError) -> bool {
    let PgError::Db { message, .. } = err else {
        return false;
    };
    bind_param_index(message).is_none()
        && params.iter().filter(|p| retry_param(p).is_some()).count() > 1
}

/// After the retry chain is exhausted: which parameter encodings were tried,
/// so the caller can pick a typed parameter or a cast.
fn attempts_summary(params: &[Param]) -> String {
    let tried: Vec<String> = params
        .iter()
        .enumerate()
        .filter(|(_, p)| p.typing != crate::pgvalue::Typing::Fixed)
        .map(|(i, p)| format!("${} {}", i + 1, crate::pgvalue::describe_attempts(p)))
        .collect();
    if tried.is_empty() {
        String::new()
    } else {
        format!(" Parameter encodings tried: {}", tried.join("; "))
    }
}

/// Appends the encodings tried to a bind-format error's message.
fn with_attempts(err: PgError, params: &[Param]) -> PgError {
    let ambiguous = ambiguous_bind(params, &err);
    match err {
        PgError::Db {
            code,
            severity,
            message,
            detail,
        } => PgError::Db {
            code,
            severity,
            message: format!(
                "{}.{}{}",
                message.trim_end_matches('.'),
                attempts_summary(params),
                if ambiguous {
                    " (the error names no parameter and more than one auto-typed parameter \
                     could be re-encoded, so no guess was made — pass typed params)"
                } else {
                    ""
                }
            ),
            detail,
        },
        other => other,
    }
}

fn values(params: &[Param]) -> Vec<PgValue> {
    params.iter().map(|p| p.value.clone()).collect()
}

/// Runs one parameterized statement, returning at most `max_rows` rows
/// (`truncated` says whether more existed). Bare integer/float parameters
/// that Postgres rejects with `22P03` are re-sent with narrower types
/// automatically (int8 → int4 → int2 → numeric; float8 → float4 → numeric).
pub async fn query(
    config: &Config,
    sql: String,
    params: Vec<Param>,
    max_rows: usize,
) -> Result<RawResult, PgError> {
    let outcome = bridge::host_call(config.timeout_ms, move || async move {
        let mut params = params;
        let mut attempts = 0usize;
        loop {
            match query_once(&sql, values(&params), max_rows).await {
                Err(err) if attempts < MAX_BIND_RETRIES && retype(&mut params, &err) => {
                    attempts += 1;
                }
                Err(err) if is_bind_format_error(&err) => {
                    return Err(with_attempts(err, &params));
                }
                other => return other,
            }
        }
    })
    .await?;
    outcome
}

/// One `db.query` exchange in component-model context.
async fn query_once(
    sql: &str,
    params: Vec<PgValue>,
    max_rows: usize,
) -> Result<RawResult, PgError> {
    let (columns, mut stream, done) = bindings::db::query(sql.to_owned(), params).await?;
    let mut rows = Vec::new();
    let mut truncated = false;
    while let Some(row) = stream.next().await {
        if rows.len() >= max_rows {
            truncated = true;
            break;
        }
        rows.push(row);
    }
    // Dropping the reader cancels the host's fetch task; the completion
    // future then resolves (Ok once the task notices, or with the error the
    // task hit first — which is the real outcome when nothing was cut).
    drop(stream);
    match done.await {
        Ok(()) => Ok(RawResult {
            columns,
            rows,
            truncated,
        }),
        Err(err) if truncated => {
            tracing::debug!(error = ?err, "completion error after an early stream drop");
            Ok(RawResult {
                columns,
                rows,
                truncated,
            })
        }
        Err(err) => Err(name_column(err.into(), &columns)),
    }
}

/// "column N: …" from the host → the column's name, when the header is known.
fn name_column(err: PgError, columns: &[String]) -> PgError {
    match err {
        PgError::ValueConversion {
            message,
            column: None,
        } => {
            let column = message
                .strip_prefix("column ")
                .and_then(|rest| rest.split(':').next())
                .and_then(|n| n.trim().parse::<usize>().ok())
                .and_then(|i| columns.get(i).cloned());
            PgError::ValueConversion { message, column }
        }
        other => other,
    }
}

/// Per-instance prepared-statement cache (SQL text → host token), bounded
/// and least-recently-used. Statics survive across requests on a warm
/// instance, which is exactly the lifetime of the host's token table for
/// this component.
fn prepared_cache() -> &'static Mutex<Vec<(String, String)>> {
    use std::sync::OnceLock;
    static CACHE: OnceLock<Mutex<Vec<(String, String)>>> = OnceLock::new();
    CACHE.get_or_init(|| Mutex::new(Vec::new()))
}

const PREPARED_CACHE_SIZE: usize = 64;

fn cached_token(sql: &str) -> Option<String> {
    let mut cache = prepared_cache().lock().ok()?;
    let pos = cache.iter().position(|(s, _)| s == sql)?;
    let entry = cache.remove(pos);
    let token = entry.1.clone();
    cache.push(entry);
    Some(token)
}

fn remember_token(sql: &str, token: &str) {
    if let Ok(mut cache) = prepared_cache().lock() {
        cache.retain(|(s, _)| s != sql);
        if cache.len() >= PREPARED_CACHE_SIZE {
            cache.remove(0);
        }
        cache.push((sql.to_owned(), token.to_owned()));
    }
}

fn forget_token(sql: &str) {
    if let Ok(mut cache) = prepared_cache().lock() {
        cache.retain(|(s, _)| s != sql);
    }
}

/// Runs one writing/DDL statement through `db-prepared` (prepare once per
/// instance, then exec) and returns the number of rows affected. Handles the
/// host evicting the token (re-prepares once) and the same `22P03` retries as
/// [`query`].
pub async fn execute(config: &Config, sql: String, params: Vec<Param>) -> Result<u64, PgError> {
    let outcome = bridge::host_call(config.timeout_ms, move || async move {
        let mut params = params;
        let mut attempts = 0usize;
        let mut reprepared = false;
        let mut token = match cached_token(&sql) {
            Some(t) => t,
            None => prepare(&sql).await?,
        };
        loop {
            match bindings::db_prepared::exec(token.clone(), values(&params)).await {
                Ok(n) => return Ok(n),
                Err(WitError::UnknownPreparedStatement) if !reprepared => {
                    reprepared = true;
                    forget_token(&sql);
                    token = prepare(&sql).await?;
                }
                Err(err) => {
                    let err = PgError::from(err);
                    if attempts < MAX_BIND_RETRIES && retype(&mut params, &err) {
                        attempts += 1;
                        continue;
                    }
                    if is_bind_format_error(&err) {
                        return Err(with_attempts(err, &params));
                    }
                    return Err(err);
                }
            }
        }
    })
    .await?;
    outcome
}

async fn prepare(sql: &str) -> Result<String, PgError> {
    let token = bindings::db_prepared::prepare(sql.to_owned()).await?;
    remember_token(sql, &token);
    Ok(token)
}

/// Runs a multi-statement script with no parameters on one connection
/// (single implicit transaction unless the script has its own BEGIN/COMMIT).
pub async fn execute_batch(config: &Config, sql: String) -> Result<(), PgError> {
    let outcome = bridge::host_call(config.timeout_ms, move || async move {
        bindings::db::query_batch(sql).await.map_err(PgError::from)
    })
    .await?;
    outcome
}
