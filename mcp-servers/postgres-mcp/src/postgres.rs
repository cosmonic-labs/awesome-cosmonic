/// Named configuration read from the environment (see deploy/workload.yaml).
#[derive(Debug, Clone)]
pub struct Config {
    /// `POSTGRES_ALLOW_WRITES` == "true".
    pub allow_writes: bool,
    /// `POSTGRES_DEFAULT_ROW_LIMIT` (default 100).
    pub default_row_limit: usize,
    /// `POSTGRES_MAX_ROW_LIMIT` (default 1000).
    pub max_row_limit: usize,
    /// `POSTGRES_QUERY_TIMEOUT_MS` (default 30000).
    pub timeout_ms: u64,
    /// `POSTGRES_MAX_RESULT_BYTES` (default 1 MiB).
    pub max_result_bytes: usize,
    /// `POSTGRES_DEFAULT_SCHEMA` (default `public`).
    pub default_schema: String,
    /// `POSTGRES_HIDE_SYSTEM_SCHEMAS` != "false".
    pub hide_system_schemas: bool,
}

impl Config {
    pub fn from_env() -> Self {
        fn num<T: std::str::FromStr + Ord>(key: &str, default: T, lo: T, hi: T) -> T {
            std::env::var(key)
                .ok()
                .and_then(|v| v.trim().parse::<T>().ok())
                .unwrap_or(default)
                .clamp(lo, hi)
        }
        let max_row_limit = num("POSTGRES_MAX_ROW_LIMIT", 1000usize, 1, 100_000);
        Self {
            allow_writes: std::env::var("POSTGRES_ALLOW_WRITES")
                .is_ok_and(|v| v.trim().eq_ignore_ascii_case("true")),
            default_row_limit: num("POSTGRES_DEFAULT_ROW_LIMIT", 100usize, 1, max_row_limit),
            max_row_limit,
            timeout_ms: num("POSTGRES_QUERY_TIMEOUT_MS", 30_000u64, 1_000, 600_000),
            max_result_bytes: num(
                "POSTGRES_MAX_RESULT_BYTES",
                1024usize * 1024,
                4096,
                16 * 1024 * 1024,
            ),
            default_schema: std::env::var("POSTGRES_DEFAULT_SCHEMA")
                .ok()
                .map(|s| s.trim().to_owned())
                .filter(|s| !s.is_empty())
                .unwrap_or_else(|| "public".to_owned()),
            hide_system_schemas: !std::env::var("POSTGRES_HIDE_SYSTEM_SCHEMAS")
                .is_ok_and(|v| v.trim().eq_ignore_ascii_case("false")),
        }
    }

    /// Effective settings, for `server_info` and error messages.
    pub fn summary(&self) -> Value {
        json!({
            "writes_allowed": self.allow_writes,
            "default_row_limit": self.default_row_limit,
            "max_row_limit": self.max_row_limit,
            "query_timeout_ms": self.timeout_ms,
            "max_result_bytes": self.max_result_bytes,
            "default_schema": self.default_schema,
            "hide_system_schemas": self.hide_system_schemas,
            "max_cell_chars": crate::pgvalue::MAX_CELL_CHARS,
        })
    }
}

// ── errors ──────────────────────────────────────────────────────────────────

/// Everything that can go wrong between a tool and the database.
#[derive(Debug, Clone)]
pub enum PgError {
    /// The database rejected or failed the statement (`query-failed`).
    Db {
        code: String,
        severity: String,
        message: String,
        detail: Option<String>,
    },
    /// The host could not get/keep a connection (`connection-failed`); also
    /// where tokio-postgres client-side errors land (parameter encoding).
    ConnectionFailed(String),
    /// Host-side parameter validation (`invalid-params`).
    InvalidParams(String),
    /// Host-side statement rejection (`invalid-query`).
    InvalidQuery(String),
    /// A column could not be converted to a `pg-value` — the whole result
    /// is discarded (`value-conversion-failed`). `column` is the name when
    /// the query's column list was already known.
    ValueConversion {
        message: String,
        column: Option<String>,
    },
    /// Prepared-statement token unknown (after the automatic re-prepare).
    UnknownPrepared,
    /// The host refused this component access to the database.
    AccessDenied,
    /// The host's own time limit.
    HostTimeout,
    /// Backend-specific failure (`other`).
    Other(String),
    /// The component's deadline (`POSTGRES_QUERY_TIMEOUT_MS`) elapsed.
    Deadline(u64),
    /// The bridge went away (component teardown / client gone).
    BridgeClosed,
    /// Refused locally before reaching the host (inspector, params).
    Refused(String),
}

impl PgError {
    /// A rendering-time failure (a cell the host mis-decoded).
    pub fn cell(column: Option<&str>, reason: &str) -> Self {
        let col = column.map(|c| format!(" `{c}`")).unwrap_or_default();
        PgError::Refused(format!(
            "result column{col} cannot be rendered: {reason}. The host reads numeric/decimal/money \
             columns through a lossy path (binary bytes as text); cast the column in SQL — \
             `col::text` keeps the exact value, `col::float8` gives a JSON number — and use \
             describe_table to see column types first"
        ))
    }
}

impl From<WitError> for PgError {
    fn from(err: WitError) -> Self {
        match err {
            WitError::ConnectionFailed(m) => PgError::ConnectionFailed(m),
            WitError::InvalidParams(m) => PgError::InvalidParams(m),
            WitError::InvalidQuery(m) => PgError::InvalidQuery(m),
            WitError::QueryFailed(DbError {
                code,
                severity,
                message,
                detail,
                ..
            }) => PgError::Db {
                code,
                severity,
                message,
                detail,
            },
            WitError::ValueConversionFailed(m) => PgError::ValueConversion {
                message: m,
                column: None,
            },
            WitError::UnknownPreparedStatement => PgError::UnknownPrepared,
            WitError::AccessDenied => PgError::AccessDenied,
            WitError::Timeout => PgError::HostTimeout,
            WitError::Other(m) => PgError::Other(m),
        }
    }
}

impl From<HostCallError> for PgError {
    fn from(err: HostCallError) -> Self {
        match err {
            HostCallError::TimedOut(ms) => PgError::Deadline(ms),
            HostCallError::BridgeClosed => PgError::BridgeClosed,
        }
    }
}

impl PgError {
    /// SQLSTATE, when the database reported one.
    pub fn sqlstate(&self) -> Option<&str> {
        match self {
            PgError::Db { code, .. } => Some(code),
            _ => None,
        }
    }

    /// Short machine-readable kind for structured errors.
    pub fn kind(&self) -> &'static str {
        match self {
            PgError::Db { .. } => "query_failed",
            PgError::ConnectionFailed(_) => "connection_failed",
            PgError::InvalidParams(_) => "invalid_params",
            PgError::InvalidQuery(_) => "invalid_query",
            PgError::ValueConversion { .. } => "value_conversion_failed",
            PgError::UnknownPrepared => "unknown_prepared_statement",
            PgError::AccessDenied => "access_denied",
            PgError::HostTimeout => "host_timeout",
            PgError::Other(_) => "other",
            PgError::Deadline(_) => "timeout",
            PgError::BridgeClosed => "bridge_closed",
            PgError::Refused(_) => "refused",
        }
    }

    /// The client-facing message: what happened, then what to do about it.
    pub fn render(&self) -> String {
        match self {
            PgError::Db {
                code,
                severity,
                message,
                detail,
            } => {
                let mut out = format!("{severity} {code} ({}): {message}", sqlstate_name(code));
                if let Some(d) = detail.as_deref().filter(|d| !d.is_empty()) {
                    out.push_str(&format!(" — {}", d.trim_end_matches('.')));
                }
                if let Some(hint) = sqlstate_hint(code, message) {
                    out.push_str(&format!(". Hint: {hint}"));
                }
                out
            }
            PgError::ConnectionFailed(m) => format!(
                "connection failed: {m}. Hint: {}",
                connection_hint(m)
            ),
            PgError::InvalidParams(m) => format!(
                "invalid parameters: {m}. Hint: params are positional ($1..$n, in order); pass typed \
                 values as {{\"type\": \"int4\"|\"uuid\"|\"timestamptz\"|…, \"value\": …}} where the \
                 column type is not text/int8/float8/bool — describe_table shows column types"
            ),
            PgError::InvalidQuery(m) => format!("the host rejected the statement: {m}"),
            PgError::ValueConversion { message, column } => {
                let name = column
                    .as_deref()
                    .map(|n| format!(" (`{n}`)"))
                    .unwrap_or_default();
                let expr = column.clone().unwrap_or_else(|| "col".to_owned());
                format!(
                    "the host cannot convert a result column{name}: {message}. The whole result \
                     is discarded when any column has a type the host's value conversion does not \
                     handle: numeric/decimal/money (most values), enum, char(n), oid/regclass/\
                     regproc, interval, timetz, range/multirange, circle/line, void (pg_sleep), \
                     record, tsquery/tsvector. Hint: cast it in SQL (`{expr}::text` — exact for \
                     numeric —, `{expr}::float8`, intervals `EXTRACT(EPOCH FROM {expr})`, oids \
                     `{expr}::int`), avoid SELECT * on unfamiliar tables, and use describe_table to \
                     see column types first"
                )
            }
            PgError::UnknownPrepared => "the prepared statement was evicted by the host and could \
                 not be re-prepared; retry the call once"
                .to_owned(),
            PgError::AccessDenied => "access denied: the host refused this component's access to \
                 the database. Hint: check the workload's wasmcloud:postgres hostInterfaces (db, \
                 db-prepared) and Desktop policy, then re-apply"
                .to_owned(),
            PgError::HostTimeout => "the host's time limit expired before the call completed. \
                 Hint: narrow the query (WHERE/LIMIT), explain_query first, or raise \
                 statement_timeout via the URL options"
                .to_owned(),
            PgError::Other(m) => {
                if m.contains("no database configured for this component") {
                    format!(
                        "{m}. The component reached the daemon through an UNNAMED postgres import \
                         (legacy path); this build must import `db` / `db-prepared` labels and the \
                         workload must declare hostInterfaces with those names — rebuild \
                         (cosmonic_inspect must list `db` and `db-prepared`), re-promote, re-apply"
                    )
                } else {
                    format!("database backend error: {m}")
                }
            }
            PgError::Deadline(ms) => format!(
                "timeout: no result within {ms} ms (POSTGRES_QUERY_TIMEOUT_MS). The row stream was \
                 dropped so the host stopped fetching, but the statement may still be running on \
                 the server. Hint: add WHERE/LIMIT, run explain_query first, set \
                 `options=-c statement_timeout=30000` (URL-encoded) in the connection URL so Postgres \
                 cancels runaway statements (they then fail with 57014), or raise \
                 POSTGRES_QUERY_TIMEOUT_MS"
            ),
            PgError::BridgeClosed => "the request ended before the database call completed (client \
                 disconnected or component shutting down); retry"
                .to_owned(),
            PgError::Refused(m) => m.clone(),
        }
    }

    /// Structured form for `structuredContent` alongside the message.
    pub fn to_json(&self) -> Value {
        json!({
            "error": self.kind(),
            "sqlstate": self.sqlstate(),
            "message": self.render(),
        })
    }
}

/// Human name of the common SQLSTATEs (the rest fall back to the class).
